import type { EquipmentSlotId, RarityId } from "../model/ids";
import type { ItemDefinition } from "../model/content-types";

function item(
  id: string,
  name: string,
  kind: ItemDefinition["kind"],
  rarity: RarityId,
  slot: EquipmentSlotId | null,
  value: number,
  extras?: Partial<ItemDefinition>,
): ItemDefinition {
  return {
    id,
    name,
    kind,
    rarity,
    slot,
    attackIds: extras?.attackIds ?? [],
    grantedAbilityIds: extras?.grantedAbilityIds ?? [],
    value,
    stackSize: extras?.stackSize ?? 1,
    tags: extras?.tags ?? [],
    useAbilityId: extras?.useAbilityId ?? null,
  };
}

