export function familyForDimension(id: DimensionNumber, dimensions = DIMENSIONS): FamilyId {
  const row = dimensions.find((dimension) => dimension.id === id);
  if (!row) {
    throw new Error(`Unknown dimension ${id}`);
  }
  return row.family;
}

export function familyForPlane(plane: PlanePair): FamilyId {
  return familyForDimension(plane.b);
}
