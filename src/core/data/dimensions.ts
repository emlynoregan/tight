const ALL_CHANNELS: readonly AttackChannelId[] = [
  "physical",
  "finesse",
  "endurance",
  "speed",
  "divine",
  "arcane",
  "social",
  "psychic",
];

function channels(
  modifiers: Partial<Record<AttackChannelId, PlaneFamilyDefinition["channelModifiers"][AttackChannelId]>>,
): PlaneFamilyDefinition["channelModifiers"] {
  const result = {} as Record<AttackChannelId, PlaneFamilyDefinition["channelModifiers"][AttackChannelId]>;
  for (const channel of ALL_CHANNELS) {
    result[channel] = modifiers[channel] ?? "normal";
  }
  return result;
}

