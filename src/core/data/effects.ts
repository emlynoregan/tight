function ability(
  id: string,
  name: string,
  attackId: string | null,
  effectOrBundleId: string | null,
  cooldown: number,
  tags: readonly string[],
  kind: AbilityDefinition["kind"],
  acquisitionClass?: string,
): AbilityDefinition {
  return acquisitionClass === undefined
    ? { id, name, attackId, effectOrBundleId, cooldown, tags, kind }
    : { id, name, attackId, effectOrBundleId, cooldown, tags, kind, acquisitionClass };
}

